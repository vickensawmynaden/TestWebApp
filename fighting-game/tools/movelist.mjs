// Prints every fighter's command list and combo routes as Markdown, from the same normalised
// move data the simulation, move list and training HUD use.  node tools/movelist.mjs > docs/COMMANDS.md
import { CHARACTERS, ROSTER } from '../js/sim/characters.js';
import { movesFor } from '../js/sim/movedata.js';

const KIND = { true: 'true combo', string: 'string with a gap', juggle: 'launch combo', ch: 'counter-hit only' };
const out = ['# Command lists', '', 'Generated by `node tools/movelist.mjs` from the game data (`js/sim/characters.js` through `js/sim/movedata.js`).',
  'Notation: f/b/u/d = toward/away/up/down, 1 LP · 2 RP · 3 LK · 4 RK, `,` = string follow-up, `▸` = next move after recovery (link), CH = counter hit.',
  'Advantage is for the attacker hitting on its first active frame. Damage of routes is measured in the simulation (tests/combos.test.js).', ''];
for (const id of ROSTER) {
  const c = CHARACTERS[id];
  const { list } = movesFor(c);
  out.push(`## ${c.fullName} — ${c.style}`, '', '| Move | Command | Level | Dmg | Startup | Block | Hit | CH | Role |', '|---|---|---|---|---|---|---|---|---|');
  for (const m of list) {
    if (m.cmd === 'auto') continue;
    const cmd = m.cmd === 'air' ? 'jump + any' : m.inString ? `↳ ${m.cmd}` : m.cmd;
    const blk = m.level === 'throw' ? `break with ${m.breakMask === 1 ? '1' : '2'}` : m.display.block;
    out.push(`| ${m.name}${m.rage ? ' (Rage Art)' : ''} | \`${cmd}\` | ${m.level} | ${m.dmg || ''} | ${m.display.startup} | ${blk} | ${m.display.hit} | ${m.display.ch} | ${m.level === 'throw' || m.level === 'parry' ? '' : m.role} |`);
  }
  const strings = list.flatMap((m) => m.stringSpecs.map((s) => `${m.name} (\`${m.cmd}\`) → ${list.find((x) => x.id === s.to)?.name} (\`${s.cmd}\`): input window frames ${s.window[0]}–${s.window[1]}, starts on frame ${s.exec}` +
    (s.on.length < 4 ? `, only on ${s.on.join('/')}` : '') + (s.target !== 'any' ? `, only vs ${s.target} opponent` : '')));
  if (strings.length) out.push('', '**String follow-ups**', '', ...strings.map((x) => `- ${x}`));
  if (c.combos?.length) {
    out.push('', '**Combo routes**', '', '| Route | Input | Type | Hits | Damage | Notes |', '|---|---|---|---|---|---|');
    for (const r of c.combos) out.push(`| ${r.name} (${r.role}) | \`${r.notation}\` | ${KIND[r.kind]} | ${r.hits} | ${r.damage} | ${r.note || ''} |`);
  }
  out.push('');
}
console.log(out.join('\n'));
